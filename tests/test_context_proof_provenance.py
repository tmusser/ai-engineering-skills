from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ECO = ROOT / "scripts" / "eco_budget.py"
MANIFEST = ROOT / "scripts" / "context_manifest.py"
COMMAND = "python -m pytest tests/test_export.py"


def check(name: str, *, command: str = COMMAND, status: str = "PASS",
          exit_code: int | None = 0, source: str = "command",
          provenance: bool = True) -> dict[str, object]:
    record: dict[str, object] = {
        "check": name, "command": command, "exit_code": exit_code,
        "evidence_source": source, "status": status,
        "evidence": "tests completed with expected result",
    }
    if provenance:
        record["recorded_at"] = "2026-11-08T20:00:00Z"
    return record


def verify_document(*checks: dict[str, object]) -> str:
    payload = json.dumps({"schema_version": 1, "checks": list(checks)})
    fence = chr(96) * 3
    return (
        "# Verify\n\n## Verify gate\n\nStatus: PASS\n\n"
        "## Structured verification evidence\n\n"
        + fence + "json\n" + payload + "\n" + fence + "\n"
    )


class ProofProvenanceTests(unittest.TestCase):
    def setUp(self) -> None:
        context = tempfile.TemporaryDirectory()
        self.addCleanup(context.cleanup)
        self.root = Path(context.name)
        self.spec = self.root / "SPEC.md"
        self.verify = self.root / "VERIFY.md"
        self.notes = self.root / "notes.md"
        self.manifest = self.root / "manifest.json"
        self.spec.write_text(
            "# Spec\n\n## Acceptance criteria\n\n- Maintain CSV layout.\n\n"
            "## Commands\n\n- Test: " + COMMAND + "\n",
            encoding="utf-8",
        )
        self.verify.write_text(verify_document(check("export-test")), encoding="utf-8")
        self.notes.write_text(COMMAND + " has NOT been executed yet.\n", encoding="utf-8")

    def run_eco(self, *args: str, stdin: bytes | None = None) -> tuple[int, dict]:
        run = subprocess.run(
            [sys.executable, str(ECO), "--root", str(self.root),
             "--format", "json", *args],
            input=stdin, capture_output=True, check=False,
        )
        if run.returncode == 2:
            return 2, {"error": run.stderr.decode("utf-8")}
        return run.returncode, json.loads(run.stdout)

    def recorded(self, *paths: str, source: str = "VERIFY.md", proof: str = COMMAND):
        return self.run_eco(
            *paths, "--proof-mode", "recorded",
            "--verification-source", source, "--require-proof", proof,
        )

    def make_packet(self, *, tamper: bool = False, metadata_only: bool = False) -> Path:
        rows = self.verify.read_text(encoding="utf-8").splitlines()
        excerpt = "\n".join(rows)
        digest = "sha256:" + hashlib.sha256(excerpt.encode("utf-8")).hexdigest()
        if tamper:
            excerpt = excerpt.replace("tests completed", "NEVER completed")
        packet = self.root / "packet.md"
        tick = chr(96)
        body = (
            "### " + tick + "VERIFY.md" + tick + " 1-" + str(len(rows)) + "\n\n"
            "- Source role: required\n"
            "- Content hash: " + digest + "\n\n"
            "~~~~md\n" + excerpt.rstrip() + "\n~~~~\n"
        )
        packet.write_text(
            "<!-- generated by scripts/context_pack.py -->\n\n"
            "# Context Packet\n\n- Packet status: PASS\n\n"
            "- Required sources: VERIFY.md=represented\n\n"
            "## Relevant excerpts\n\n"
            + ("" if metadata_only else body)
            + "\n## Omitted candidates\n\n- None.\n",
            encoding="utf-8",
        )
        return packet

    def test_old_literal_mode_still_accepts_mentioned_command(self) -> None:
        code, result = self.run_eco(str(self.notes), "--require-proof", COMMAND)
        self.assertEqual(code, 0, result)
        self.assertEqual(result["sufficiency"]["proofs"][0]["status"], "represented")

    def test_unexecuted_note_is_not_recorded_proof(self) -> None:
        code, result = self.recorded(str(self.notes))
        self.assertEqual(code, 3, result)
        self.assertEqual(result["sufficiency"]["proofs"][0]["status"], "missing")

    def test_exact_pass_with_provenance_is_recorded(self) -> None:
        code, result = self.recorded(str(self.verify))
        self.assertEqual(code, 0, result)
        self.assertEqual(result["sufficiency"]["proof_mode"], "recorded")
        self.assertEqual(result["sufficiency"]["proofs"][0]["checks"], ["export-test"])

    def test_stdin_and_other_file_cannot_impersonate_source(self) -> None:
        copy = self.root / "copy.md"
        copy.write_text(self.verify.read_text(encoding="utf-8"), encoding="utf-8")
        for path, stdin in ((str(copy), None), ("-", copy.read_bytes())):
            with self.subTest(path=path):
                code, _ = self.run_eco(
                    path, "--proof-mode", "recorded", "--require-proof", COMMAND,
                    stdin=stdin,
                )
                self.assertEqual(code, 3)

    def test_partial_command_reference_not_exact_proof(self) -> None:
        code, result = self.recorded(str(self.verify), proof="pytest")
        self.assertEqual(code, 3, result)

    def test_failed_inferred_and_invalid_provenance_cannot_pass(self) -> None:
        examples = (
            verify_document(check("failed", status="FAIL", exit_code=1)),
            verify_document(check("inferred", source="inferred", exit_code=None)),
            verify_document(check("contradiction", status="PASS", exit_code=1)),
            verify_document(check("missing-provenance", provenance=False)),
        )
        for document in examples:
            with self.subTest(document=document[:100]):
                self.verify.write_text(document, encoding="utf-8")
                code, result = self.recorded(str(self.verify))
                self.assertEqual(code, 3, result)
                self.assertEqual(result["sufficiency"]["proofs"][0]["status"], "missing")

    def test_pass_and_fail_for_same_command_requires_review(self) -> None:
        self.verify.write_text(
            verify_document(check("success"), check("failed", status="FAIL", exit_code=1)),
            encoding="utf-8",
        )
        code, result = self.recorded(str(self.verify))
        self.assertEqual(code, 3, result)

    def test_prose_or_malformed_structured_data_cannot_pass(self) -> None:
        examples = (
            "# Verify\n\n## Command evidence\n- Command: " + COMMAND + "\n- Exit code: 0\n",
            verify_document(check("test")).replace('"schema_version": 1', '"schema_version": 2'),
        )
        for document in examples:
            with self.subTest(document=document[:80]):
                self.verify.write_text(document, encoding="utf-8")
                code, _ = self.recorded(str(self.verify))
                self.assertEqual(code, 3)

    def test_valid_source_verified_packet_can_carry_record(self) -> None:
        packet = self.make_packet()
        code, result = self.recorded(str(packet))
        self.assertEqual(code, 0, result)
        self.assertEqual(result["sufficiency"]["proofs"][0]["checks"], ["export-test"])

    def test_tampered_or_metadata_only_packet_fails_closed(self) -> None:
        for options in ({"tamper": True}, {"metadata_only": True}):
            with self.subTest(options=options):
                packet = self.make_packet(**options)
                code, _ = self.recorded(str(packet))
                self.assertEqual(code, 3)

    def test_stale_packet_after_source_edit_requires_review(self) -> None:
        packet = self.make_packet()
        self.verify.write_text(verify_document(check("changed")), encoding="utf-8")
        code, result = self.recorded(str(packet))
        self.assertEqual(code, 3, result)
        self.assertIn("differs", str(result["sufficiency"]["warnings"]))

    def test_manifest_proofs_can_be_strengthened_without_schema_change(self) -> None:
        proposed = subprocess.run(
            [sys.executable, str(MANIFEST), "--root", str(self.root), "--spec",
             "SPEC.md", "--output", str(self.manifest)],
            capture_output=True, text=True, check=False,
        )
        self.assertEqual(proposed.returncode, 0, proposed.stderr)
        data = json.loads(self.manifest.read_text(encoding="utf-8"))
        data["approved"] = True
        self.manifest.write_text(json.dumps(data), encoding="utf-8")
        code, result = self.run_eco(
            str(self.spec), str(self.verify),
            "--manifest", str(self.manifest), "--proof-mode", "recorded",
        )
        self.assertEqual(code, 0, result)
        self.assertEqual(result["sufficiency"]["proofs"][0]["status"], "represented")

    def test_other_source_heading_requirements_still_compose(self) -> None:
        code, result = self.run_eco(
            str(self.spec), str(self.verify), "--require-source", "SPEC.md",
            "--require-heading", "SPEC.md::Acceptance criteria",
            "--proof-mode", "recorded", "--require-proof", COMMAND,
        )
        self.assertEqual(code, 0, result)
        self.assertEqual(result["sufficiency"]["sources"][0]["status"], "represented")

    def test_no_proofs_or_unsafe_verification_file_are_input_errors(self) -> None:
        for arguments in (
            ("--proof-mode", "recorded"),
            ("--proof-mode", "recorded", "--require-proof", COMMAND,
             "--verification-source", "../VERIFY.md"),
        ):
            with self.subTest(arguments=arguments):
                code, result = self.run_eco(str(self.verify), *arguments)
                self.assertEqual(code, 2)
                self.assertTrue(result["error"])

    def test_missing_verification_source_requires_review(self) -> None:
        code, result = self.recorded(str(self.verify), source="OTHER.md")
        self.assertEqual(code, 3, result)
        self.assertEqual(result["sufficiency"]["proofs"][0]["status"], "missing")


if __name__ == "__main__":
    unittest.main()
