from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CLI = ROOT / "scripts" / "eco_budget.py"
SPEC = """# Spec

## Objective

Add optional CSV filtering.

## Acceptance criteria

- With a matching region, export its orders.

### No-match invariant

- With zero matches, emit header-only CSV.

## Invalid if

- Existing headers change.
"""


class SectionAwareContextTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        (self.root / "SPEC.md").write_text(SPEC, encoding="utf-8")

    def check(self, *arguments: str, stdin: bytes | None = None):
        result = subprocess.run(
            [sys.executable, str(CLI), "--root", str(self.root), "--format", "json", *arguments],
            input=stdin, capture_output=True, check=False,
        )
        if result.returncode == 2:
            return 2, {"error": result.stderr.decode()}
        return result.returncode, json.loads(result.stdout)

    def make_packet(self, start: int, end: int, *, status: str = "PASS",
                    tamper: bool = False, fence: str = "````") -> Path:
        lines = SPEC.splitlines()
        chunk = "\n".join(lines[start - 1:end])
        digest = "sha256:" + hashlib.sha256(chunk.encode("utf-8")).hexdigest()
        if tamper:
            chunk = chunk.replace("header-only", "data-only")
        packet = self.root / "packet.md"
        packet.write_text(
            "<!-- generated by scripts/context_pack.py -->\n\n# Context Packet\n\n"
            f"- Packet status: {status}\n"
            "- Required sources: SPEC.md=represented\n\n"
            "## Selected context\n\n"
            "| Source role | File | Lines |\n| --- | --- | --- |\n"
            f"| required | SPEC.md | {start}-{end} |\n\n"
            "## Relevant excerpts\n\n"
            f"### `SPEC.md` {start}-{end}\n\n"
            "- Source role: required\n"
            f"- Content hash: {digest}\n\n"
            f"{fence}md\n{chunk}\n{fence}\n\n"
            "## Omitted candidates\n\n- None.\n",
            encoding="utf-8",
        )
        return packet

    def test_direct_file_covers_unique_headings(self) -> None:
        code, report = self.check(
            str(self.root / "SPEC.md"),
            "--require-heading", "SPEC.md::Acceptance criteria",
            "--require-heading", "SPEC.md::Invalid if",
        )
        self.assertEqual(code, 0, report)
        self.assertEqual(
            [item["status"] for item in report["sufficiency"]["headings"]],
            ["represented", "represented"],
        )

    def test_objective_excerpt_does_not_cover_acceptance_criteria(self) -> None:
        packet = self.make_packet(3, 6)
        code, report = self.check(str(packet), "--require-heading",
                                  "SPEC.md::Acceptance criteria")
        self.assertEqual(code, 3, report)
        self.assertEqual(report["sufficiency"]["headings"][0]["status"], "missing")

    def test_complete_nested_section_covers_only_itself(self) -> None:
        lines = SPEC.splitlines()
        start = lines.index("## Acceptance criteria") + 1
        end = lines.index("## Invalid if")
        packet = self.make_packet(start, end)
        code, report = self.check(str(packet), "--require-heading",
                                  "SPEC.md::Acceptance criteria")
        self.assertEqual(code, 0, report)
        self.assertEqual(report["sufficiency"]["headings"][0]["status"], "represented")
        code, report = self.check(str(packet), "--require-heading",
                                  "SPEC.md::Invalid if")
        self.assertEqual(code, 3, report)

    def test_partial_section_cannot_pass(self) -> None:
        lines = SPEC.splitlines()
        start = lines.index("## Acceptance criteria") + 1
        for end in (start, start + 2):
            with self.subTest(end=end):
                packet = self.make_packet(start, end)
                code, report = self.check(str(packet), "--require-heading",
                                          "SPEC.md::Acceptance criteria")
                self.assertEqual(code, 3, report)

    def test_tampered_or_warn_packet_causes_review(self) -> None:
        lines = SPEC.splitlines()
        start = lines.index("## Acceptance criteria") + 1
        end = lines.index("## Invalid if")
        for options in ({"tamper": True}, {"status": "WARN"}):
            with self.subTest(options=options):
                packet = self.make_packet(start, end, **options)
                code, report = self.check(str(packet), "--require-heading",
                                          "SPEC.md::Acceptance criteria")
                self.assertEqual(code, 3, report)

    def test_tilde_fences_from_hydrator_are_supported(self) -> None:
        lines = SPEC.splitlines()
        start = lines.index("## Acceptance criteria") + 1
        end = lines.index("## Invalid if")
        packet = self.make_packet(start, end, fence="~~~~")
        code, report = self.check(str(packet), "--require-heading",
                                  "SPEC.md::Acceptance criteria")
        self.assertEqual(code, 0, report)

    def test_missing_or_ambiguous_heading_causes_review(self) -> None:
        for extra, heading in (
            ("", "Nonexistent section"),
            ("\n## Acceptance criteria\n\n- Second copy.\n", "Acceptance criteria"),
            ("\n```md\n## Tricky Heading\n```\n", "Tricky Heading"),
        ):
            with self.subTest(heading=heading, extra=extra):
                (self.root / "SPEC.md").write_text(SPEC + extra, encoding="utf-8")
                code, report = self.check(str(self.root / "SPEC.md"),
                                          "--require-heading", f"SPEC.md::{heading}")
                self.assertEqual(code, 3, report)
                self.assertEqual(report["sufficiency"]["headings"][0]["status"], "missing")

    def test_text_mentions_and_stdin_cannot_impersonate_source(self) -> None:
        note = self.root / "notes.md"
        note.write_text("SPEC.md::Acceptance criteria", encoding="utf-8")
        for args, stdin in (
            ((str(note),), None),
            (("-",), SPEC.encode("utf-8")),
        ):
            with self.subTest(args=args):
                code, report = self.check(*args, "--require-heading",
                                          "SPEC.md::Acceptance criteria", stdin=stdin)
                self.assertEqual(code, 3, report)

    def test_combines_with_source_proof_and_budget(self) -> None:
        code, report = self.check(
            str(self.root / "SPEC.md"), "--require-source", "SPEC.md",
            "--require-proof", "header-only CSV",
            "--require-heading", "SPEC.md::Acceptance criteria",
            "--max-bytes", "4",
        )
        self.assertEqual(code, 3, report)
        self.assertEqual(report["sufficiency"]["headings"][0]["status"], "represented")
        self.assertEqual(report["sufficiency"]["sources"][0]["status"], "represented")
        self.assertEqual(report["sufficiency"]["proofs"][0]["status"], "represented")

    def test_bad_heading_operand_is_an_input_error(self) -> None:
        for entry in ("SPEC.md", "SPEC.md::", "../SPEC.md::Acceptance criteria",
                      "SPEC.md::Acceptance criteria::nested", "/etc/passwd::Config"):
            with self.subTest(entry=entry):
                code, _ = self.check(str(self.root / "SPEC.md"), "--require-heading", entry)
                self.assertEqual(code, 2)


if __name__ == "__main__":
    unittest.main()
