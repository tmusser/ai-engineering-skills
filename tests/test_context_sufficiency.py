from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ECO = ROOT / "scripts" / "eco_budget.py"


class ContextSufficiencyTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        (self.root / "SPEC.md").write_text(
            "# Spec\n\n## Acceptance criteria\n\n- Export stays header-only on no matches.\n",
            encoding="utf-8",
        )
        (self.root / "VERIFY.md").write_text(
            "# Verify\n\n## Proof target\n\npython -m pytest tests/test_export.py\n",
            encoding="utf-8",
        )

    def run_eco(self, *args: str, stdin: bytes | None = None) -> tuple[int, dict]:
        result = subprocess.run(
            [sys.executable, str(ECO), "--root", str(self.root), "--format", "json", *args],
            input=stdin, capture_output=True,
        )
        if result.returncode == 2:
            return 2, {"error": result.stderr.decode()}
        return result.returncode, json.loads(result.stdout)

    def make_packet(self, *, source: str = "SPEC.md", status: str = "PASS",
                    tamper: bool = False, metadata_only: bool = False) -> Path:
        source_text = (self.root / source).read_text(encoding="utf-8").rstrip()
        rows = source_text.splitlines()
        digest = "sha256:" + hashlib.sha256(source_text.encode()).hexdigest()
        body = (
            f"### `{source}` 1-{len(rows)}\n\n"
            "- Source role: required\n"
            f"- Content hash: {digest}\n\n"
            "```md\n"
            + (source_text.replace("header-only", "data-only") if tamper else source_text)
            + "\n```\n"
        )
        if metadata_only:
            body = ""
        packet = self.root / "packet.md"
        packet.write_text(
            "<!-- generated by scripts/context_pack.py -->\n\n"
            "# Context Packet\n\n"
            f"- Packet status: {status}\n"
            "- Required sources: SPEC.md=represented\n\n"
            "## Selected context\n\n"
            "| Source role | File | Lines |\n"
            "| --- | --- | --- |\n"
            f"| required | {source} | 1-{len(rows)} |\n\n"
            "## Relevant excerpts\n\n" + body + "\n## Omitted candidates\n\n"
            "- None.\n",
            encoding="utf-8",
        )
        return packet

    def test_existing_byte_only_mode_remains_unchanged(self) -> None:
        code, report = self.run_eco(str(self.root / "SPEC.md"), "--max-bytes", "60000")
        self.assertEqual(code, 0)
        self.assertEqual(report["status"], "PASS")
        self.assertNotIn("sufficiency", report)

    def test_direct_files_cover_required_sources_and_proof(self) -> None:
        code, report = self.run_eco(
            str(self.root / "SPEC.md"), str(self.root / "VERIFY.md"),
            "--require-source", "SPEC.md", "--require-source", "VERIFY.md",
            "--require-proof", "python -m pytest tests/test_export.py",
        )
        self.assertEqual(code, 0)
        self.assertTrue(all(row["status"] == "represented"
                            for kind in ("sources", "proofs") for row in report["sufficiency"][kind]))

    def test_missing_source_fails_even_if_filename_is_mentioned(self) -> None:
        note = self.root / "note.md"
        note.write_text("SPEC.md is required but not included", encoding="utf-8")
        code, report = self.run_eco(str(note), "--require-source", "SPEC.md")
        self.assertEqual(code, 3)
        self.assertEqual(report["sufficiency"]["sources"][0]["status"], "missing")

    def test_missing_proof_and_stdin_presence(self) -> None:
        code, report = self.run_eco("-", "--require-proof", "tests/test_export.py",
                                    stdin=b"The plan has no focused test yet")
        self.assertEqual(code, 3)
        self.assertEqual(report["sufficiency"]["proofs"][0]["status"], "missing")
        code, report = self.run_eco("-", "--require-proof", "tests/test_export.py",
                                    stdin=b"Proof target: tests/test_export.py")
        self.assertEqual(code, 0)

    def test_verified_excerpt_from_generated_packet_covers_source(self) -> None:
        packet = self.make_packet()
        code, report = self.run_eco(str(packet), "--require-source", "SPEC.md",
                                    "--require-proof", "header-only on no matches")
        self.assertEqual(code, 0, report)
        self.assertEqual(report["sufficiency"]["sources"][0]["status"], "represented")

    def test_metadata_only_or_tampered_excerpt_does_not_pass(self) -> None:
        for options in ({"metadata_only": True}, {"tamper": True}):
            with self.subTest(options=options):
                packet = self.make_packet(**options)
                code, report = self.run_eco(str(packet), "--require-source", "SPEC.md",
                                            "--require-proof", "header-only on no matches")
                self.assertEqual(code, 3)
                self.assertEqual(report["sufficiency"]["sources"][0]["status"], "missing")

    def test_stale_source_and_packet_warn_fail_review(self) -> None:
        packet = self.make_packet()
        (self.root / "SPEC.md").write_text("different current spec\n", encoding="utf-8")
        code, report = self.run_eco(str(packet), "--require-source", "SPEC.md")
        self.assertEqual(code, 3)
        self.assertTrue(report["sufficiency"]["warnings"])
        for status in ("WARN", "FAIL"):
            with self.subTest(status=status):
                packet = self.make_packet(status=status)
                code, report = self.run_eco(str(packet), "--require-source", "SPEC.md")
                self.assertEqual(code, 3)
                self.assertTrue(report["sufficiency"]["warnings"])

    def test_byte_budget_also_enforced_when_sufficient(self) -> None:
        code, report = self.run_eco(str(self.root / "SPEC.md"), "--require-source", "SPEC.md",
                                    "--max-bytes", "5")
        self.assertEqual(code, 3)
        self.assertEqual(report["sufficiency"]["sources"][0]["status"], "represented")

    def test_valid_missing_source_requires_review_not_input_error(self) -> None:
        code, report = self.run_eco(
            str(self.root / "SPEC.md"),
            "--require-source", "missing.md",
        )
        self.assertEqual(code, 3)
        self.assertEqual(report["status"], "REVIEW_REQUIRED")
        self.assertEqual(
            report["sufficiency"]["sources"],
            [{"source": "missing.md", "status": "missing"}],
        )

    def test_existing_directory_is_invalid_not_missing(self) -> None:
        (self.root / "a-directory").mkdir()
        code, report = self.run_eco(
            str(self.root / "SPEC.md"),
            "--require-source", "a-directory",
        )
        self.assertEqual(code, 2)

    def test_invalid_requirements_fail_closed(self) -> None:
        for source in ("../outside.md", "/tmp/thing", "a//b.md"):
            with self.subTest(source=source):
                code, report = self.run_eco(str(self.root / "SPEC.md"),
                                            "--require-source", source)
                self.assertEqual(code, 2)
        code, report = self.run_eco(str(self.root / "SPEC.md"), "--require-proof", "")
        self.assertEqual(code, 2)


if __name__ == "__main__":
    unittest.main()
