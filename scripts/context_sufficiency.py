#!/usr/bin/env python3
"""Inspect selected eco-mode text for named sources and literal proof anchors.

No content is auto-loaded. These checks establish representation, not relevance,
semantic completeness, or the validity of the tests themselves.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path, PurePosixPath

PACKET_MARKER = "<!-- generated by scripts/context_pack.py -->"
HEADING = re.compile(r"(?m)^### \`(?P<path>[^\`]+)\` (?P<first>[1-9]\d*)-(?P<last>[1-9]\d*)$")
HASH = re.compile(r"(?m)^- Content hash: (sha256:[0-9a-f]{64})$")
FENCE = re.compile(r"^(\`{3,}|~{3,})[A-Za-z0-9_-]*$")


def safe_source(root: Path, name: str) -> Path:
    """Require a normalized source path bounded by the selected repository."""
    if not name or "\\" in name or any(piece in {"", ".", ".."} for piece in name.split("/")):
        raise ValueError(f"invalid required source path: {name!r}")
    pure = PurePosixPath(name)
    if pure.is_absolute() or pure.as_posix() != name:
        raise ValueError(f"required source must be repository-relative: {name}")
    resolved_root = root.resolve()
    path = (resolved_root / name).resolve()
    if not path.is_relative_to(resolved_root):
        raise ValueError(f"required source escapes repository root: {name}")
    if not path.is_file():
        raise ValueError(f"required source is not a regular file: {name}")
    return path


def verified_excerpts(packet: str, root: Path) -> tuple[dict[str, list[str]], list[str]]:
    """Check real excerpt text, hashes and line ranges; never trust metadata alone."""
    found: dict[str, list[str]] = {}
    warnings: list[str] = []
    status = re.search(r"(?m)^- Packet status: (PASS|WARN|FAIL)$", packet)
    if status is None:
        return found, ["packet status missing"]
    if status.group(1) != "PASS":
        warnings.append(f"packet status is {status.group(1)}")
    if "\n## Relevant excerpts\n" not in packet:
        return found, warnings + ["packet excerpts missing"]
    region = packet.split("\n## Relevant excerpts\n", 1)[1].split("\n## Omitted candidates\n", 1)[0]
    headings = list(HEADING.finditer(region))
    for idx, match in enumerate(headings):
        name = match.group("path")
        first, last = int(match.group("first")), int(match.group("last"))
        block = region[match.end():headings[idx + 1].start() if idx + 1 < len(headings) else len(region)]
        if last < first:
            warnings.append(f"invalid excerpt range: {name}")
            continue
        try:
            source = safe_source(root, name)
            rows = source.read_text(encoding="utf-8").splitlines()
        except (ValueError, UnicodeError, OSError):
            warnings.append(f"excerpt source unavailable: {name}")
            continue
        if last > len(rows):
            warnings.append(f"stale excerpt range: {name} {first}-{last}")
            continue
        source_excerpt = "\n".join(rows[first - 1:last])
        expected_hash = "sha256:" + hashlib.sha256(source_excerpt.encode("utf-8")).hexdigest()
        claimed_hash = HASH.search(block)
        lines = block.splitlines()
        opening = next((i for i, line in enumerate(lines) if FENCE.fullmatch(line)), None)
        if opening is None or claimed_hash is None:
            warnings.append(f"excerpt hash or body missing: {name}")
            continue
        fence = FENCE.fullmatch(lines[opening]).group(1)
        closing = next((i for i in range(opening + 1, len(lines)) if lines[i] == fence), None)
        if closing is None:
            warnings.append(f"excerpt closing fence missing: {name}")
            continue
        rendered = "\n".join(lines[opening + 1:closing])
        if claimed_hash.group(1) != expected_hash or rendered != source_excerpt.rstrip():
            warnings.append(f"excerpt differs from current source: {name}")
            continue
        found.setdefault(name, []).append(rendered)
    return found, warnings


def check_sufficiency(
    payloads: list[tuple[str, str]], root: Path,
    required_sources: list[str], required_proofs: list[str],
) -> dict[str, object]:
    """Return evidence only for selected files and verified packet excerpts."""
    sources = {name: safe_source(root, name) for name in required_sources}
    direct: set[Path] = set()
    represented: set[str] = set()
    proof_texts: list[str] = []
    warnings: list[str] = []
    for label, contents in payloads:
        if not contents.startswith(PACKET_MARKER):
            if label != "<stdin>":
                path = Path(label).resolve()
                if path in sources.values():
                    direct.add(path)
            proof_texts.append(contents)
            continue
        excerpts, packet_warnings = verified_excerpts(contents, root)
        warnings.extend(packet_warnings)
        for name, slices in excerpts.items():
            represented.add(name)
            proof_texts.extend(slices)
    return {
        "sources": [
            {"source": name, "status": "represented" if path in direct or name in represented else "missing"}
            for name, path in sources.items()
        ],
        "proofs": [
            {"proof": text, "status": "represented" if any(text in selected for selected in proof_texts) else "missing"}
            for text in required_proofs
        ],
        "warnings": warnings,
    }
